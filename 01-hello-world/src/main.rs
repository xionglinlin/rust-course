// `main` 函数是每个 Rust 程序的入口点
// 用 `fn` 关键字声明函数
fn main() {
    // `println!` 是一个"宏"（以 ! 结尾的都是宏），负责向终端打印一行
    // 字符串用双引号包裹
    println!("Hello, world!");

    // 字符串里可以放占位符 {}，后面的参数会依次填入
    println!("我叫 {}, 今年 {} 岁", "小明", 18);

    // 可以给占位符编号，重复使用同一个参数
    println!("{0} 喜欢 {1}，{1} 也喜欢 {0}", "小明", "小红");

    // 也可以给占位符命名（需要指定参数名）
    println!("{name} 正在学习 {lang}", name = "小明", lang = "Rust");

    // 数字的格式化：{:?} 调试输出，{:.2} 保留两位小数
    println!("圆周率约等于 {:.2}", 3.1415926);

    // 程序执行到这里就结束了，返回值 0 表示成功
}
