// ============================================
// 第 22 课：宏 —— macro_rules! 声明式宏
// ============================================

// 宏 vs 函数：宏是"写代码的代码"（元编程）。
// 函数：运行时接收值，返回值。
// 宏：编译期接收【语法片段】，生成代码。
// 你从第一课就在用宏：println!、vec!、format!、println!、todo!……
//
// 两种宏：
//   1. 声明式宏 macro_rules!：模式匹配语法片段，生成代码（本课）
//   2. 过程宏（proc macro）：函数式处理 TokenStream，见 derive 等（本课只提概念）

// ============================================
// 例 1：最简宏 —— 定义常量表达式
// ============================================
macro_rules! say_hello {
    // () 表示"匹配空参数"，=> 后面是生成的代码
    () => {
        println!("Hello from a macro!")
    };
}

// ============================================
// 例 2：带参数的宏 —— 实现自己的 vec!
// ============================================
// $(...)* 表示"重复任意次"；$x:expr 表示"匹配一个表达式，绑定到变量 x"
macro_rules! my_vec {
    // 模式1：my_vec!() → 空 Vec
    () => {
        Vec::new()
    };
    // 模式2：my_vec![1, 2, 3] → vec![1, 2, 3]
    // $( $x:expr ),* 匹配逗号分隔的任意个表达式；$(...)* 展开为重复的 push
    ( $( $x:expr ),* ) => {
        {
            let mut temp_vec = Vec::new();
            $(
                temp_vec.push($x);
            )*
            temp_vec
        }
    };
    // 模式3：my_vec![0; 5] → 5 个 0
    ( $elem:expr ; $n:expr ) => {
        std::vec::from_elem($elem, $n)
    };
}

// ============================================
// 例 3：日志宏 —— 带文件名/行号（函数做不到！）
// ============================================
// file!() line!() column!() 是内置宏，展开为编译期常量
macro_rules! log_info {
    ($msg:expr) => {
        println!("[INFO] {}:{} {}", file!(), line!(), $msg)
    };
}

// ============================================
// 例 4：重复匹配 + 模式分支 —— 支持 1~3 个参数
// ============================================
macro_rules! greet {
    ($name:expr) => {
        println!("你好，{}！", $name)
    };
    ($name:expr, $greeting:expr) => {
        println!("{}，{}！", $greeting, $name)
    };
}

// ============================================
// 例 5a：真正的宏递归 —— 基于 token 列表收缩
// ============================================
// count!(a, b, c) 展开为 1 + count!(b, c) 展开为 1 + count!(c) 展开为 1 + count!()
// 每次展开 token 列表变短，必然终止（宏递归必须靠"结构变小"，不能靠计算）
macro_rules! count {
    () => { 0 }; // 出口：没有 token 了
    ($head:tt $(, $tail:tt)*) => { 1 + count!($($tail),*) };
}

// ============================================
// 例 5b：宏生成"函数" —— 阶乘的务实写法
// ============================================
// ⚠️ 错误示范：factorial!(5) 会无限递归（5-1 永远不是字面量 0）
// 正确做法：宏负责"生成代码"，计算交给生成的函数/循环
macro_rules! make_factorial {
    ($name:ident) => {
        fn $name(n: u64) -> u64 {
            let mut result = 1;
            for i in 2..=n {
                result *= i;
            }
            result
        }
    };
}

// 用宏生成一个函数
make_factorial!(factorial);

// ============================================
// 例 6：返回值宏 —— 宏可以"算出"一个值
// ============================================
macro_rules! max_of {
    ($a:expr, $b:expr) => {
        if $a > $b { $a } else { $b }
    };
}

fn main() {
    // ---------- 1. 最简宏 ----------
    say_hello!();

    // ---------- 2. 自己的 vec! ----------
    let empty: Vec<i32> = my_vec![];
    let v1 = my_vec![1, 2, 3];
    let v2 = my_vec![1, 2, 3, 4, 5];
    let zeros = my_vec![0; 5];
    println!("空: {:?}", empty);
    println!("v1: {:?}", v1);
    println!("v2: {:?}", v2);
    println!("zeros: {:?}", zeros);
    // 对比标准库 vec! 的两种形式
    println!("std vec![1,2,3] = {:?}, vec![9; 3] = {:?}", vec![1, 2, 3], vec![9; 3]);

    // ---------- 3. 日志宏：函数做不到的 file!/line! ----------
    log_info!("用户登录成功");
    log_info!("数据已保存");

    // ---------- 4. 多模式宏 ----------
    greet!("小明");
    greet!("小明", "早上好");

    // ---------- 5. 宏递归与宏生成函数 ----------
    println!("count!(a, b, c, d) = {}", count!(a, b, c, d)); // 4
    println!("5! = {}", factorial(5)); // 宏生成的函数，120

    // ---------- 6. 返回值宏 ----------
    let m = max_of!(10, 20);
    println!("max_of!(10, 20) = {}", m);

    // ---------- 7. 宏和函数的本质区别 ----------
    println!("\n--- 宏 vs 函数 ---");
    println!("1. 宏在【编译期】展开，函数在运行时执行");
    println!("2. 宏能操作语法（匹配任意表达式、重复、递归生成）");
    println!("3. 宏能拿到 file!/line! 等编译期信息");
    println!("4. 宏可以接收变长参数（println! 的参数个数不定）");
    println!("5. 代价：宏难调试（展开后才知道代码长啥样）");
    println!("   cargo expand 插件可以查看宏展开结果");

    // ---------- 8. 过程宏概念 ----------
    println!("\n--- 过程宏（proc macro）---");
    println!("derive 宏：#[derive(Debug)] 自动生成 impl 代码");
    println!("属性宏：#[tokio::main]、#[test]");
    println!("函数宏：类似 macro_rules 但用代码处理 token");
    println!("它们本质是：输入 TokenStream，输出 TokenStream 的函数");
    println!("过程宏必须放在独立 crate 里（本课不展开，概念先行）");
}

